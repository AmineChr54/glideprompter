// Builds the browser version into docs/app/ (served by GitHub Pages).
// It reuses the desktop renderer files unchanged and swaps Electron's preload for web/bridge.js.
// Usage: npm run web
const fs = require('fs');
const path = require('path');

const root = path.join(__dirname, '..');
const out = path.join(root, 'docs', 'app');
fs.rmSync(out, { recursive: true, force: true });
fs.mkdirSync(path.join(out, 'shared'), { recursive: true });

const copy = (from, to = from) => fs.copyFileSync(path.join(root, from), path.join(out, to));
for (const f of ['output.css', 'output.js', 'control.css', 'control.js']) copy(f);
for (const f of fs.readdirSync(path.join(root, 'shared'))) copy(path.join('shared', f));
copy(path.join('web', 'bridge.js'), 'bridge.js');

// Sample scripts bundled for first-time visitors.
const scripts = {};
for (const f of fs.readdirSync(path.join(root, 'default-scripts')).filter(f => /\.txt$/i.test(f))) {
  scripts[f] = fs.readFileSync(path.join(root, 'default-scripts', f), 'utf8');
}
fs.writeFileSync(path.join(out, 'defaults.js'),
  '// Generated by tools/build-web.js\nwindow.GP_DEFAULT_SCRIPTS = ' + JSON.stringify(scripts, null, 1) + ';\n');

const HEAD_EXTRA = '<meta name="viewport" content="width=device-width, initial-scale=1">\n<link rel="icon" href="../img/favicon.png">\n';
function page(src, dest, role, title) {
  let html = fs.readFileSync(path.join(root, src), 'utf8');
  const before = html;
  html = html.replace('<html>', `<html lang="en" data-role="${role}">`)
    .replace(/<title>.*<\/title>/, `<title>${title}</title>`)
    .replace('<meta charset="utf-8">\n', '<meta charset="utf-8">\n' + HEAD_EXTRA)
    .replace('<script src="shared/parse.js"></script>',
      (role === 'control' ? '<script src="defaults.js"></script>\n' : '') +
      '<script src="shared/defaults.js"></script>\n<script src="bridge.js"></script>\n<script src="shared/parse.js"></script>');
  if (html === before || !html.includes('bridge.js')) throw new Error('could not patch ' + src);
  html = html.replace(/^<!doctype html>\r?\n/i, `<!doctype html>\n<!-- Generated by tools/build-web.js from ${src}. Edit the source, not this file. -->\n`);
  fs.writeFileSync(path.join(out, dest), html);
}
page('control.html', 'index.html', 'control', 'GlidePrompter Web');
page('output.html', 'output.html', 'output', 'GlidePrompter Output');
console.log('web app built in', path.relative(root, out));
